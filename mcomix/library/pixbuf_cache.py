""" pixbuf_cache.py - Caches book covers for the library display."""


import functools
import threading
from collections import OrderedDict

from gi.repository import GdkPixbuf

__all__ = ["get_pixbuf_cache"]

class _PixbufCache:

    """ Pixbuf cache for the library window. Instead of loading book covers
    from disk again after switching collection or using filtering, this class
    stores a pre-defined amount of pixbufs in memory, evicting the least
    recently used pixbufs as necessary.
    """

    def __init__(self, size: int) -> None:
        #: Cache size, in images
        assert size > 0
        self.cachesize = size
        #: Store book path => pixbuf, least recently used entry first
        self._cache: OrderedDict[str, GdkPixbuf.Pixbuf] = OrderedDict()
        #: Ensure thread safety: covers are generated by worker threads.
        self._lock = threading.RLock()

    def add(self, id: str, pixbuf: GdkPixbuf.Pixbuf) -> None:
        """ Adds a cache object with <id> and associates it with the
        passed pixbuf. """

        with self._lock:
            self._cache[id] = pixbuf
            self._cache.move_to_end(id)
            while len(self._cache) > self.cachesize:
                self._cache.popitem(last=False)

    def get(self, id: str) -> "GdkPixbuf.Pixbuf | None":
        """ Returns the pixbuf for the given cache id, or None, if such
        an entry does not exist. """
        with self._lock:
            if id not in self._cache:
                return None
            self._cache.move_to_end(id)
            return self._cache[id]

    def invalidate(self, id: str) -> None:
        """ Invalidates the object with the specified cache ID. """
        with self._lock:
            self._cache.pop(id, None)

    def invalidate_all(self) -> None:
        """ Invalidates all cached objects. """
        with self._lock:
            self._cache.clear()


@functools.cache
def get_pixbuf_cache() -> _PixbufCache:
    """The one cache every book area draws its covers through."""
    # 500 items is about 130 MB of RAM with 500px thumbnails,
    # and about 35 MB at 250px.
    return _PixbufCache(500)

